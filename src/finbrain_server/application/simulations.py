"""Use cases of GARCH(1,1) simulations of asset prices."""

import random
from dataclasses import dataclass
from datetime import date, timedelta

from finbrain_server.application.cache_policy import CachePolicy
from finbrain_server.application.market import MarketDataService
from finbrain_server.application.ports import Cache, GarchEngine
from finbrain_server.domain.entities import GarchParameters, SimulationFan
from finbrain_server.domain.exceptions import InvalidParameterError, SimulationError
from finbrain_server.domain.technical import daily_returns
from finbrain_server.domain.validation import ensure_choice, ensure_range

FIT_PERIODS = ("1y", "2y", "5y")
PERCENTILES = (5, 10, 25, 50, 75, 90, 95)
VALUE_TYPES = ("open", "high", "low", "close")
MODES = ("simulate", "fit_and_simulate")
MIN_OBSERVATIONS = 30
SAMPLE_PATHS = 5
DEFAULT_SEED = 7


@dataclass(frozen=True)
class SyntheticRequest:
    """Inputs of a synthetic generation (the finbrain-mcp tool).

    Parameters
    ----------
    ticker : str
        Asset the series represent.
    start_date : date
        First business day of the series.
    n_days : int
        Business days per series (1 to 2520).
    value_type : str
        OHLC field returned.
    n_series : int
        Number of series (1 to 100).
    mode : str
        ``simulate`` or ``fit_and_simulate``.
    initial_price : float
        Price the series start from.
    manual : GarchParameters | None
        Parameters of the ``simulate`` mode.
    historical_returns : tuple[float, ...] | None
        Daily fractional returns for the ``fit_and_simulate`` mode.
    seed : int | None
        Random seed.
    """

    ticker: str
    start_date: date
    n_days: int
    value_type: str = "close"
    n_series: int = 1
    mode: str = "simulate"
    initial_price: float = 100.0
    manual: GarchParameters | None = None
    historical_returns: tuple[float, ...] | None = None
    seed: int | None = None


@dataclass(frozen=True)
class SyntheticSeries:
    """Synthetic price series generated by a GARCH(1,1) model.

    Parameters
    ----------
    dates : tuple[date, ...]
        Business days of the series.
    series : dict[str, tuple[float, ...]]
        Values by series name (``serie_1``, ``serie_2``...).
    parameters : GarchParameters
        Model used.
    value_type : str
        OHLC field returned (``open``, ``high``, ``low`` or ``close``).
    """

    dates: tuple[date, ...]
    series: dict[str, tuple[float, ...]]
    parameters: GarchParameters
    value_type: str


class SimulationService:
    """GARCH(1,1) fits on real histories and Monte Carlo price paths.

    Parameters
    ----------
    market : MarketDataService
        Source of the (cached) price histories.
    engine : GarchEngine
        Fits and simulates the model.
    cache : Cache
        Cache shared by the services.
    policy : CachePolicy
        Time to live of each kind of data.
    """

    def __init__(
        self,
        market: MarketDataService,
        engine: GarchEngine,
        cache: Cache,
        policy: CachePolicy,
    ) -> None:
        self._market = market
        self._engine = engine
        self._cache = cache
        self._policy = policy

    def fit_asset(
        self,
        ticker: str,
        history_period: str = "2y",
    ) -> tuple[GarchParameters, float, date, int]:
        """Fit a GARCH(1,1) to the daily returns of an asset.

        Parameters
        ----------
        ticker : str
            Yahoo Finance ticker.
        history_period : str
            Daily history used in the fit (``1y``, ``2y`` or ``5y``).

        Returns
        -------
        tuple[GarchParameters, float, date, int]
            Parameters, last close, day of the last close and number of
            returns used.

        Raises
        ------
        SimulationError
            When the history is too short.
        """
        ensure_choice("history_period", history_period, FIT_PERIODS)
        history = self._market.get_history(ticker, history_period, "1d")
        returns = daily_returns(history.closes)
        if len(returns) < MIN_OBSERVATIONS:
            raise SimulationError(
                f"At least {MIN_OBSERVATIONS} daily returns are needed to fit "
                f"the model; '{history.ticker}' has {len(returns)}."
            )
        parameters = self._cache.get_or_load(
            f"garch-fit:{history.ticker}:{history_period}:{history.bars[-1].date}",
            self._policy.simulation,
            lambda: self._engine.fit([value * 100 for value in returns]),
        )
        last_bar = history.bars[-1]
        return parameters, last_bar.close, last_bar.date, len(returns)

    def simulate_asset(
        self,
        ticker: str,
        horizon_days: int = 126,
        n_paths: int = 500,
        history_period: str = "2y",
        seed: int | None = None,
    ) -> SimulationFan:
        """Simulate future prices of an asset with a GARCH(1,1) fitted to it.

        The model is fitted on the real daily returns and starts from the
        last observed volatility, so calm and turbulent periods give
        narrower or wider fans.

        Parameters
        ----------
        ticker : str
            Yahoo Finance ticker.
        horizon_days : int
            Business days simulated (5 to 756).
        n_paths : int
            Number of paths (100 to 2000).
        history_period : str
            Daily history used in the fit.
        seed : int | None
            Random seed; the same inputs and seed give the same fan.

        Returns
        -------
        SimulationFan
            Percentiles per day, sample paths and final prices.

        Example
        -------
        >>> fan = service.simulate_asset("PETR4.SA", horizon_days=21)
        >>> len(fan.dates), sorted(fan.percentiles)[:2]
        (21, ['p10', 'p25'])
        """
        ensure_range("horizon_days", horizon_days, 5, 756)
        ensure_range("n_paths", n_paths, 100, 2000)
        parameters, last_close, last_date, observations = self.fit_asset(
            ticker, history_period
        )
        effective_seed = DEFAULT_SEED if seed is None else seed

        def simulate() -> SimulationFan:
            returns = self._engine.simulate_returns(
                parameters, horizon_days, n_paths, effective_seed
            )
            paths = [_prices_from_returns(last_close, path) for path in returns]
            columns = list(zip(*paths))
            percentiles = {
                f"p{level}": tuple(
                    round(_percentile(column, level), 4) for column in columns
                )
                for level in PERCENTILES
            }
            return SimulationFan(
                ticker=normalize_symbol(ticker),
                last_close=last_close,
                last_date=last_date,
                dates=tuple(business_days_after(last_date, horizon_days)),
                percentiles=percentiles,
                sample_paths=tuple(
                    tuple(round(price, 4) for price in path)
                    for path in paths[:SAMPLE_PATHS]
                ),
                final_prices=tuple(round(path[-1], 4) for path in paths),
                parameters=parameters,
                n_paths=n_paths,
                observations_used=observations,
            )

        key = (
            f"garch-sim:{normalize_symbol(ticker)}:{history_period}:{last_date}:"
            f"{horizon_days}:{n_paths}:{effective_seed}"
        )
        return self._cache.get_or_load(key, self._policy.simulation, simulate)

    def generate_synthetic(self, request: SyntheticRequest) -> SyntheticSeries:
        """Generate synthetic OHLC series (the finbrain-mcp tool).

        ``mode='simulate'`` uses ``request.manual``;
        ``mode='fit_and_simulate'`` fits the model on
        ``request.historical_returns`` or, when they are not given, on two
        years of the ticker's real history.

        Parameters
        ----------
        request : SyntheticRequest
            Inputs of the generation.

        Returns
        -------
        SyntheticSeries
            Dates, series and the parameters used.

        Raises
        ------
        InvalidParameterError
            When a parameter is not accepted.
        """
        ensure_choice("value_type", request.value_type, VALUE_TYPES)
        ensure_choice("mode", request.mode, MODES)
        ensure_range("n_days", request.n_days, 1, 2520)
        ensure_range("n_series", request.n_series, 1, 100)
        ensure_range("initial_price", request.initial_price, 1e-6, 1e9)
        parameters = self._synthetic_parameters(request)
        generator = random.Random(request.seed)
        returns = self._engine.simulate_returns(
            parameters, request.n_days, request.n_series, request.seed
        )
        series = {}
        for index, path in enumerate(returns, start=1):
            candles = _candles_from_returns(path, request.initial_price, generator)
            series[f"serie_{index}"] = tuple(
                candle[request.value_type] for candle in candles
            )
        return SyntheticSeries(
            dates=tuple(business_days_from(request.start_date, request.n_days)),
            series=series,
            parameters=parameters,
            value_type=request.value_type,
        )

    def _synthetic_parameters(self, request: SyntheticRequest) -> GarchParameters:
        """Choose the parameters of a synthetic generation.

        Parameters
        ----------
        request : SyntheticRequest
            Inputs of the generation.

        Returns
        -------
        GarchParameters
            Parameters to simulate.

        Raises
        ------
        InvalidParameterError
            When the manual parameters are missing or not stationary.
        """
        manual = request.manual
        if request.mode == "simulate":
            if manual is None:
                raise InvalidParameterError("Inform mu, omega, alpha and beta.")
            if manual.omega <= 0 or manual.alpha < 0 or manual.beta < 0:
                raise InvalidParameterError("omega must be > 0; alpha, beta >= 0.")
            if manual.persistence >= 1:
                raise InvalidParameterError(
                    "alpha + beta must be < 1 (GARCH stationarity)."
                )
            return GarchParameters(manual.mu, manual.omega, manual.alpha, manual.beta)
        if request.historical_returns:
            if len(request.historical_returns) < MIN_OBSERVATIONS:
                raise InvalidParameterError(
                    "fit_and_simulate needs at least "
                    f"{MIN_OBSERVATIONS} historical returns."
                )
            fitted = self._engine.fit(
                [value * 100 for value in request.historical_returns]
            )
        else:
            fitted = self.fit_asset(request.ticker, "2y")[0]
        return GarchParameters(fitted.mu, fitted.omega, fitted.alpha, fitted.beta)


def normalize_symbol(ticker: str) -> str:
    """Upper-case a ticker for keys and responses.

    Parameters
    ----------
    ticker : str
        Ticker received.

    Returns
    -------
    str
        The ticker stripped and in upper case.
    """
    return str(ticker).strip().upper()


def business_days_from(
    start: date,
    count: int,
) -> list[date]:
    """Business days (Monday to Friday) starting on ``start``.

    Parameters
    ----------
    start : date
        First candidate day.
    count : int
        Number of days returned.

    Returns
    -------
    list[date]
        Days in chronological order.
    """
    days = []
    day = start
    while len(days) < count:
        if day.weekday() < 5:
            days.append(day)
        day += timedelta(days=1)
    return days


def business_days_after(
    last: date,
    count: int,
) -> list[date]:
    """Business days strictly after ``last``.

    Parameters
    ----------
    last : date
        Last observed day.
    count : int
        Number of days returned.

    Returns
    -------
    list[date]
        Days in chronological order.
    """
    return business_days_from(last + timedelta(days=1), count)


def _prices_from_returns(
    start_price: float,
    returns_percent: list[float],
) -> list[float]:
    """Compound daily returns into prices.

    Parameters
    ----------
    start_price : float
        Price before the first return.
    returns_percent : list[float]
        Daily returns in percent.

    Returns
    -------
    list[float]
        One price per return.
    """
    prices = []
    price = start_price
    for value in returns_percent:
        price *= max(1 + value / 100, 0.01)
        prices.append(price)
    return prices


def _candles_from_returns(
    returns_percent: list[float],
    initial_price: float,
    generator: random.Random,
) -> list[dict[str, float]]:
    """Turn daily returns into OHLC candles with random wicks.

    Parameters
    ----------
    returns_percent : list[float]
        Daily returns in percent.
    initial_price : float
        Open of the first candle.
    generator : random.Random
        Source of the wick sizes.

    Returns
    -------
    list[dict[str, float]]
        Candles with ``open``, ``high``, ``low`` and ``close``.
    """
    candles = []
    price = initial_price
    for value in returns_percent:
        change = value / 100
        day_open = price
        day_close = day_open * max(1 + change, 0.01)
        spread = abs(change) / 2 + 1e-4
        day_high = max(day_open, day_close) * (1 + abs(generator.gauss(0, spread)))
        day_low = min(day_open, day_close) * (1 - min(abs(generator.gauss(0, spread)), 0.5))
        candles.append({
            "open": round(day_open, 4),
            "high": round(day_high, 4),
            "low": round(day_low, 4),
            "close": round(day_close, 4),
        })
        price = day_close
    return candles


def _percentile(
    values: tuple[float, ...],
    level: float,
) -> float:
    """Percentile with linear interpolation (as ``numpy.percentile``).

    Parameters
    ----------
    values : tuple[float, ...]
        Sample.
    level : float
        Percentile between 0 and 100.

    Returns
    -------
    float
        Interpolated percentile.
    """
    ordered = sorted(values)
    position = (len(ordered) - 1) * level / 100
    lower = int(position)
    upper = min(lower + 1, len(ordered) - 1)
    weight = position - lower
    return ordered[lower] * (1 - weight) + ordered[upper] * weight
